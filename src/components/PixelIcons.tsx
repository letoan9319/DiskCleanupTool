function pixelIcon(asset: string) {
  return function PixelIcon({ className = "", style, ...props }: HTMLAttributes<HTMLSpanElement>) {
    return <span {...props} aria-hidden="true" className={`pixel-icon ${className}`}
      style={{ maskImage: `url("${asset}")`, ...style }} />;
  };
}

